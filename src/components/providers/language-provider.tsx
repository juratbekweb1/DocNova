type Translations = { [K in keyof typeof translations.en]: string };

interface LanguageContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translations;
}

const LanguageContext = createContext<LanguageContextType>({
  lang: "uz",
  setLang: () => {},
  t: translations.uz,
});

export function LanguageProvider({
  children,
  initialLang = "uz",
}: {
  children: React.ReactNode;
  initialLang?: Lang;
}) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  // Sync state with localStorage on client mount if available
  useEffect(() => {
    try {
      const saved = localStorage.getItem("DocNova-lang") as Lang;
      if (saved && (saved === "uz" || saved === "ru" || saved === "en" || saved === "tr")) {
        if (saved !== lang) {
          // eslint-disable-next-line react-hooks/set-state-in-effect
          setLangState(saved);
        }
        document.cookie = `NEXT_LOCALE=${saved}; path=/; max-age=31536000; SameSite=Lax`;
      }
    } catch (e) {
      console.error(e);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("DocNova-lang", l);
      document.cookie = `NEXT_LOCALE=${l}; path=/; max-age=31536000; SameSite=Lax`;
    } catch (e) {
      console.error(e);
    }
    // Instant reload so all server and client components immediately switch language!
    if (typeof window !== "undefined") {
      window.location.reload();
    }
  };

  return (
    <LanguageContext.Provider
      value={{ lang, setLang, t: (translations[lang] || translations.uz) as Translations }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
